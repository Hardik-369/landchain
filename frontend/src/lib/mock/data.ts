/** Deterministic mock hash generator so server and client render identically. */
function mockHash(seed: string, length = 64): string {
  let acc = 2166136261;
  let out = "";
  for (let i = 0; i < length; i += 1) {
    const code = seed.charCodeAt(i % seed.length) + i * 31;
    acc = (acc ^ code) >>> 0;
    acc = Math.imul(acc, 16777619) >>> 0;
    out += (acc % 16).toString(16);
  }
  return out;
}

function docs(seed: string, names: string[], baseDate: string): PropertyDocument[] {
  return names.map((name, index) => ({
    id: `${seed}-doc-${index + 1}`,
    name,
    type: name.includes("Deed")
      ? "PDF"
      : name.includes("Certificate")
        ? "PDF"
        : "PDF",
    hash: mockHash(`${seed}:${name}`),
    size: `${(0.8 + index * 0.7).toFixed(1)} MB`,
    uploadedAt: new Date(
      new Date(baseDate).getTime() + index * 2 * 24 * 60 * 60 * 1000,
    ).toISOString(),
  }));
}

